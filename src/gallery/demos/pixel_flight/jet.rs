#[doc = " Decodes once into caller-owned storage. Empty entries stay transparent."]
pub fn decode(out: &mut [u8; WIDTH * LENGTH * LAYERS]) {
    let mut offset = 0;
    for pair in RUNS.chunks_exact(2) {
        let end = offset + usize::from(pair[0]);
        out[offset..end].fill(pair[1]);
        offset = end;
    }
    assert_eq!(offset, out.len());
}

#[derive(Clone, Copy)]
pub struct Voxel {
    pub x: u8,
    pub y: u8,
    pub color: u8,
}

impl Voxel {
    pub fn a(self) -> Fixed {
        Fixed::from_ratio(i32::from(self.x) * 2 - (WIDTH - 1) as i32, 2)
    }
    pub fn b(self) -> Fixed {
        PIVOT[0] - Fixed::from_int(i32::from(self.y))
    }
}

const fn voxel_count() -> usize {
    let mut count = 0;
    let mut i = 0;
    while i < RUNS.len() {
        if RUNS[i + 1] != 0 {
            count += RUNS[i] as usize;
        }
        i += 2;
    }
    count
}

const COUNT: usize = voxel_count();
static VOXELS: [Voxel; COUNT] = {
    let mut out = [Voxel {
        x: 0,
        y: 0,
        color: 0,
    }; COUNT];
    let mut cell = 0;
    let mut used = 0;
    let mut run = 0;
    while run < RUNS.len() {
        let end = cell + RUNS[run] as usize;
        while cell < end {
            if RUNS[run + 1] != 0 {
                out[used] = Voxel {
                    x: (cell % WIDTH) as u8,
                    y: ((cell / WIDTH) % LENGTH) as u8,
                    color: RUNS[run + 1],
                };
                used += 1;
            }
            cell += 1;
        }
        run += 2;
    }
    out
};

const STARTS: [usize; LAYERS + 1] = {
    let mut out = [0; LAYERS + 1];
    let mut cell = 0;
    let mut run = 0;
    while run < RUNS.len() {
        let end = cell + RUNS[run] as usize;
        while cell < end {
            if RUNS[run + 1] != 0 {
                out[cell / (WIDTH * LENGTH) + 1] += 1;
            }
            cell += 1;
        }
        run += 2;
    }
    let mut i = 1;
    while i <= LAYERS {
        out[i] += out[i - 1];
        i += 1;
    }
    out
};

pub fn slices() -> [&'static [Voxel]; LAYERS] {
    core::array::from_fn(|i| &VOXELS[STARTS[i]..STARTS[i + 1]])
}

const fn coarse_color(
    cells: &[u8; WIDTH * LENGTH * LAYERS],
    x: usize,
    y: usize,
    layer: usize,
) -> u8 {
    let mut counts = [0u8; 4];
    let mut shades = [0u16; 4];
    let mut i = 0;
    while i < 4 {
        let color = cells[layer * WIDTH * LENGTH + (y + i / 2) * WIDTH + x + i % 2];
        if color != 0 {
            let material = ((color - 1) >> 4) as usize;
            counts[material] += 1;
            shades[material] += color as u16;
        }
        i += 1;
    }
    let mut material = 0;
    i = 1;
    while i < counts.len() {
        if counts[i] >= counts[material] {
            material = i;
        }
        i += 1;
    }
    let count = counts[material] as u16;
    match (shades[material] + count / 2).checked_div(count) {
        Some(color) => color as u8,
        None => 0,
    }
}

const COARSE_COLORS: [u8; WIDTH * LENGTH * LAYERS / 4] = {
    let mut cells = [0; WIDTH * LENGTH * LAYERS];
    let mut cell = 0;
    let mut run = 0;
    while run < RUNS.len() {
        let end = cell + RUNS[run] as usize;
        while cell < end {
            cells[cell] = RUNS[run + 1];
            cell += 1;
        }
        run += 2;
    }
    let mut out = [0; WIDTH * LENGTH * LAYERS / 4];
    let mut layer = 0;
    while layer < LAYERS {
        let mut y = 0;
        while y < LENGTH {
            let mut x = 0;
            while x < WIDTH {
                out[layer * WIDTH * LENGTH / 4 + y / 2 * (WIDTH / 2) + x / 2] =
                    coarse_color(&cells, x, y, layer);
                x += 2;
            }
            y += 2;
        }
        layer += 1;
    }
    out
};

const COARSE_STARTS: [usize; LAYERS + 1] = {
    let colors = COARSE_COLORS;
    let mut out = [0; LAYERS + 1];
    let mut cell = 0;
    while cell < colors.len() {
        if colors[cell] != 0 {
            out[cell / (WIDTH * LENGTH / 4) + 1] += 1;
        }
        cell += 1;
    }
    let mut layer = 1;
    while layer <= LAYERS {
        out[layer] += out[layer - 1];
        layer += 1;
    }
    out
};

static COARSE_VOXELS: [Voxel; COARSE_STARTS[LAYERS]] = {
    let colors = COARSE_COLORS;
    let mut out = [Voxel {
        x: 0,
        y: 0,
        color: 0,
    }; COARSE_STARTS[LAYERS]];
    let mut used = 0;
    let mut layer = 0;
    while layer < LAYERS {
        let mut y = 0;
        while y < LENGTH {
            let mut x = 0;
            while x < WIDTH {
                let color = colors[layer * WIDTH * LENGTH / 4 + y / 2 * (WIDTH / 2) + x / 2];
                if color != 0 {
                    out[used] = Voxel {
                        x: x as u8,
                        y: y as u8,
                        color,
                    };
                    used += 1;
                }
                x += 2;
            }
            y += 2;
        }
        layer += 1;
    }
    out
};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(super) enum Detail {
    Full,
    Coarse,
}

impl Detail {
    pub(super) fn for_scale(scale: Fixed) -> Self {
        if scale > Fixed::ZERO && scale <= Fixed::from_ratio(3, 2) {
            Self::Coarse
        } else {
            Self::Full
        }
    }

    pub(super) fn cell_scale(self) -> Fixed {
        match self {
            Self::Full => Fixed::ONE,
            Self::Coarse => Fixed::from_int(2),
        }
    }

    pub(super) fn center_offset(self) -> Fixed {
        match self {
            Self::Full => Fixed::ZERO,
            Self::Coarse => Fixed::from_ratio(1, 2),
        }
    }

    pub(super) fn slice(self, layer: usize) -> &'static [Voxel] {
        match self {
            Self::Full => &VOXELS[STARTS[layer]..STARTS[layer + 1]],
            Self::Coarse => &COARSE_VOXELS[COARSE_STARTS[layer]..COARSE_STARTS[layer + 1]],
        }
    }
}

pub(super) struct Projections {
    pub shadow: [u8; WIDTH * LENGTH],
    pub top: [u8; WIDTH * LENGTH],
}

pub(super) static PROJECTIONS: Projections = {
    let mut out = Projections {
        shadow: [0; WIDTH * LENGTH],
        top: [0; WIDTH * LENGTH],
    };
    let mut i = VOXELS.len();
    while i > 0 {
        i -= 1;
        let voxel = &VOXELS[i];
        let at = voxel.y as usize * WIDTH + voxel.x as usize;
        out.shadow[at] = 1;
        if out.top[at] == 0 {
            let color = (voxel.color - 1) >> 4;
            out.top[at] = 1 + if color > 2 { 2 } else { color };
        }
    }
    out
};
