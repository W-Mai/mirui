use core::any::TypeId;

use crate::ecs::{Entity, World};

use super::{HistoryOutput, Output, Outputs};

mod sealed {
    pub trait Source {}
    impl Source for crate::ecs::Entity {}
    impl Source for Option<crate::ecs::Entity> {}
}

/// Entity-valued fields accepted by component output declarations.
#[doc(hidden)]
pub trait OutputSource: sealed::Source {
    fn output_source(&self) -> Option<Entity>;
}

impl OutputSource for Entity {
    fn output_source(&self) -> Option<Entity> {
        Some(*self)
    }
}

impl OutputSource for Option<Entity> {
    fn output_source(&self) -> Option<Entity> {
        *self
    }
}

/// Static output requirements generated by `#[component]`.
#[doc(hidden)]
#[derive(Clone, Copy)]
pub struct OutputDependency {
    pub(crate) descriptor: OutputDescriptor,
    pub(crate) source: fn(&World, Entity) -> Option<Entity>,
    pub(crate) retain_previous: bool,
}

impl OutputDependency {
    pub const fn current<T: Output>(source: fn(&World, Entity) -> Option<Entity>) -> Self {
        Self {
            descriptor: OutputDescriptor::of::<T>(),
            source,
            retain_previous: false,
        }
    }

    pub const fn previous<T: HistoryOutput>() -> Self {
        Self {
            descriptor: OutputDescriptor::of::<T>(),
            source: |_, owner| Some(owner),
            retain_previous: true,
        }
    }
}

#[derive(Clone, Copy)]
pub(crate) struct OutputDescriptor {
    pub(crate) kind: fn() -> TypeId,
    pub(crate) install: fn(&mut World),
    pub(crate) set_demand: fn(&World, Entity, usize, usize),
    pub(crate) invalidate: fn(&World, Entity),
    pub(crate) reset: fn(&World, Entity),
    pub(crate) version: fn(&World, Entity) -> Option<u64>,
    pub(crate) reconcile: fn(&World),
}

impl OutputDescriptor {
    const fn of<T: Output>() -> Self {
        Self {
            kind: TypeId::of::<T>,
            install: T::install,
            set_demand: |world, entity, current, history| {
                if let Some(outputs) = world.resource::<Outputs<T>>() {
                    if let Err(error) = outputs.set_demand(entity, current, history) {
                        crate::warn!(target: "mirui::outputs", "output demand rejected: {:?}", error);
                    }
                }
            },
            invalidate: |world, entity| {
                if let Some(outputs) = world.resource::<Outputs<T>>() {
                    outputs.invalidate(entity);
                }
            },
            reset: |world, entity| {
                if let Some(outputs) = world.resource::<Outputs<T>>() {
                    outputs.reset(entity);
                }
            },
            version: |world, entity| {
                let outputs = world.resource::<Outputs<T>>()?;
                let state = outputs.state(entity)?;
                state.current_available.then_some(state.current?.version)
            },
            reconcile: T::reconcile,
        }
    }
}
